/** Future destinations get a themed composition immediately, with no image API,
 * network request, shared fallback, subscription, or first-visit delay. */
export function widgetArtworkTheme(route: string, label = ''): WidgetArtworkTheme {
  const identity = widgetArtworkIdentity(route);
  const reviewed = Object.prototype.hasOwnProperty.call(WIDGET_ARTWORK_MOTIFS, identity);
  const text = `${identity} ${label}`.normalize('NFKD').toLowerCase();
  const motif = reviewed ? WIDGET_ARTWORK_MOTIFS[identity]
    : THEMES.find(([pattern]) => pattern.test(text))?.[1] ?? ['puzzle', 'sparkles'];
  const colors: WidgetArtworkTheme['colors'] = /^\/pflege/.test(identity) ? ['#b3fcf0', '#1bcab8', '#086b83']
    : /^\/akademie/.test(identity) ? ['#e5d8ff', '#a58bff', '#5141b9']
    : /^\/robotics/.test(identity) ? ['#d2e5ff', '#799cff', '#2744a9']
    : /^\/stationaer/.test(identity) ? ['#ffe4cc', '#edac71', '#a26050']
    : /^\/beratung/.test(identity) ? ['#ffddef', '#e789b9', '#884d9f']
    : /^\/settings|\/templates/.test(identity) ? ['#cbeaff', '#58b6ed', '#3153a8']
    : /^\/assist/.test(identity) ? ['#c3f6ff', '#34cbe9', '#116d9f']
    : ['#c5efff', '#57bdff', '#245ed1'];
  return { identity, primary: motif[0], secondary: motif[1], colors, reviewed };
}
