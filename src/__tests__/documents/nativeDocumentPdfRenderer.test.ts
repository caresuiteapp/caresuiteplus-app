import { beforeEach, describe, expect, it, vi } from 'vitest';
import { jsPDF } from 'jspdf';
const f = vi.hoisted(() => ({ print: vi.fn(), remove: vi.fn() }));
vi.mock('expo-print', () => ({ printToFileAsync: f.print }));
vi.mock('expo-file-system', () => ({ File: class { exists = true; delete() { f.remove(); } } }));
vi.mock('@/lib/supabase/config', () => ({ getSupabaseConfig: () => ({ url: 'https://project.example.test' }) }));
import { renderHtmlToPdfBytes } from '@/lib/documents/documentPdfRenderer.native';
const pdf = new jsPDF(); pdf.text('Native document', 20, 20); const bytes = new Uint8Array(pdf.output('arraybuffer'));
beforeEach(() => { vi.clearAllMocks(); f.print.mockResolvedValue({ uri: 'file:///cache/generated.pdf', numberOfPages: 3, base64: Buffer.from(bytes).toString('base64') }); });
describe('native document PDF renderer', () => {
  it('prints the full HTML with page breaks and returns the actual generated bytes', async () => {
    const html = '<html><head></head><body><section data-pdf-page>First</section><section data-pdf-page>Last</section></body></html>';
    expect(await renderHtmlToPdfBytes(html)).toEqual(bytes);
    expect(f.print.mock.calls[0][0].html).toContain('First'); expect(f.print.mock.calls[0][0].html).toContain('Last');
    expect(f.print.mock.calls[0][0].html).toContain("script-src 'none'"); expect(f.print.mock.calls[0][0].base64).toBe(true);
    expect(f.remove).toHaveBeenCalledOnce();
  });
  it.each([{ base64: undefined, numberOfPages: 0 }, { base64: Buffer.from('invalid').toString('base64'), numberOfPages: 1 }])('rejects an incomplete native render and cleans its temporary file', async result => {
    f.print.mockResolvedValue({ uri: 'file:///cache/generated.pdf', ...result });
    await expect(renderHtmlToPdfBytes('<p>Original</p>')).rejects.toThrow(); expect(f.remove).toHaveBeenCalledOnce();
  });
});
