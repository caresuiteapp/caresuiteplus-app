import test from 'node:test';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {stripTypeScriptTypes} from 'node:module';
import {treatmentCareSourcesIssue,treatmentCareEntryIssue,treatmentCarePacketIssue,treatmentCareOriginalIssue,makeTreatmentCarePacket} from '../../src/lib/pflege/treatmentCarePacket.web.ts';

// These exact receipts were returned by the real quarantined Staging SQL fixture.
// Only derivative tampering cases below are constructed locally. No HTTP/browser,
// real qualification, concurrent-transaction or clinical-execution claim is made.
const evidenceFile=new URL('./fixtures/treatment-staging-synthetic-20261022.json',import.meta.url);
const evidenceBytes=readFileSync(evidenceFile);
const evidence=JSON.parse(evidenceBytes.toString('utf8'));
const provenance=JSON.parse(readFileSync(new URL('./fixtures/treatment-staging-synthetic-20261022.provenance.json',import.meta.url),'utf8'));
const packetUrl=new URL('../../src/lib/pflege/treatmentCarePacket.web.ts',import.meta.url).href;
const reviewSource=readFileSync(new URL('../../src/lib/pflege/treatmentCareReview.web.ts',import.meta.url),'utf8').replace("from './treatmentCarePacket.web'",`from '${packetUrl}'`);
const {treatmentCareReviewPacketIssue,treatmentCareReviewOriginalIssue,makeTreatmentCareReviewPacket}=await import('data:text/javascript;base64,'+Buffer.from(stripTypeScriptTypes(reviewSource,{mode:'strip'})).toString('base64'));
const clone=value=>structuredClone(value);
const foreign='00000000-0000-4000-8000-999999999999';
const saved=['receipt','revisedReceipt','payerReceipt'];

test('actual SQL evidence retains exact bytes and dated rollback/quarantine provenance',()=>{
 assert.equal(provenance.schemaVersion,1);
 assert.equal(provenance.capturedOn,'2026-10-22');
 assert.equal(provenance.evidenceSha256,createHash('sha256').update(evidenceBytes).digest('hex'));
 assert.equal(provenance.sqlFixtureSha256,'625336929d84d6bd54eed0c7b6851ec50d77897d7295134586e1b386a712c3b1');
 assert.deepEqual(provenance.appliedMigrationVersions,['20261022054115','20261022055855','20261022064007']);
 assert.deepEqual(evidence.receipt.packet,evidence.packet);
 assert.equal(evidence.receipt.requestId,evidence.packet.requestId);
 assert.deepEqual(evidence.reviewReceipt.packet,evidence.reviewPacket);
 assert.equal(evidence.reviewReceipt.requestId,evidence.reviewPacket.requestId);
});

test('retained evidence has no Auth credentials, token/session payloads or JWT strings',()=>{
 const credentialKey=/access.?token|refresh.?token|password|passwd|secret|jwt|session.?id|request\.jwt|raw_user_meta|raw_app_meta|authorization|bearer/i;
 const walk=(value,path='$')=>{if(value&&typeof value==='object'){for(const [key,child] of Object.entries(value)){assert.ok(!credentialKey.test(key),`${path}.${key}`);walk(child,`${path}.${key}`);}}else if(typeof value==='string')assert.doesNotMatch(value,/eyJ[A-Za-z0-9_-]{12,}\.eyJ[A-Za-z0-9_-]{12,}\.[A-Za-z0-9_-]+/);};
 walk(evidence);
});

for(const key of saved){
 test(`actual SQL ${key} satisfies the Web packet, source, entry and original validators`,()=>{
  const r=evidence[key],p=r.packet;
  assert.equal(treatmentCarePacketIssue(p),null);
  assert.equal(treatmentCareSourcesIssue(p.sources),null);
  assert.equal(treatmentCareEntryIssue(p.entry),null);
  assert.equal(treatmentCareOriginalIssue(r.original,p),null);
  assert.deepEqual(makeTreatmentCarePacket(p),p);
  assert.equal(r.requestId,p.requestId);
  assert.deepEqual(r.original.payload,p.entry);
  assert.equal(r.original.revision,p.expectedRevision+1);
  assert.equal(r.original.recordedBy,p.actorId);
  assert.equal(r.original.history.at(-1).reason,p.reason);
  assert.equal(r.original.history[0].id,r.original.rootId);
  // Event UUIDs are generated by SQL independently of request UUIDs.
  assert.notEqual(r.original.id,p.requestId);
  assert.equal(r.original.payload.lifecycle,'open');
  assert.deepEqual(r.original.payload.qualification,{state:'unconfirmed',performedBy:null,reviewedBy:null,evidence:'',delegation:''});
  assert.equal(r.original.payload.execution.outcome,'planned');
 });
}

test('actual append-only revision retains exactly the full prior original and history',()=>{
 const first=evidence.receipt.original,next=evidence.revisedReceipt;
 assert.deepEqual(next.packet.original,first);
 assert.equal(next.packet.expectedHeadId,first.headId);
 assert.equal(next.packet.expectedRevision,first.revision);
 assert.equal(next.original.rootId,first.rootId);
 assert.equal(next.original.history.at(-1).previousId,first.headId);
 assert.deepEqual(next.original.history.slice(0,-1),first.history);
 assert.notEqual(next.original.id,first.id);
 assert.equal(next.original.payload.title,'Revised open technical review title');
 assert.equal(first.payload.title,'Open technical source review');
});

test('actual nullable people references preserve labels and full-row hash without private profile fields',()=>{
 const p=evidence.packet;
 assert.equal(p.sources.people.length,2);
 for(const person of p.sources.people){
  assert.equal(person.clientId,p.clientId);
  assert.equal(person.orderId,null);
  assert.match(person.fingerprint,/^sha256:[a-f0-9]{64}$/);
  assert.match(person.payload.display_name,/^Synthetic /);
  assert.deepEqual(Object.keys(person.payload).sort(),['active','display_name','full_name','id','qualification_state','recorded_at','version']);
  assert.equal(person.payload.qualification_state,null);
 }
 const erased=clone(p.sources);erased.people=erased.people.map(()=>null);
 assert.ok(treatmentCareSourcesIssue(erased),'The former STRICT helper output must remain unreadable.');
});

