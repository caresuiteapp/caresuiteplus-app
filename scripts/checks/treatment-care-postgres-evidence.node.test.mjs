for(const [name,mutate] of [
 ['unanchored root',o=>{o.rootId=foreign;}],
 ['foreign historical client payload',o=>{for(const h of o.history)h.payload.clientId=foreign;o.payload.clientId=foreign;}],
 ['foreign historical order payload',o=>{for(const h of o.history)h.payload.orderId=foreign;o.payload.orderId=foreign;}],
 ['header kind contradicted by history',o=>{o.kind='payer_review';}],
 ['nonboolean void state',o=>{o.voided='false';}],
 ['duplicate historical event IDs',o=>{o.history[1].id=o.history[0].id;o.id=o.headId=o.history[0].id;}],
 ['reversed recording chronology',o=>{o.history[1].recordedAt=new Date(Date.parse(o.history[0].recordedAt)-60_000).toISOString();o.recordedAt=o.history[1].recordedAt;}],
]){
 test(`actual SQL original tampering is rejected: ${name}`,()=>{
  const original=clone(evidence.revisedReceipt.original);mutate(original);
  assert.ok(treatmentCareOriginalIssue(original,evidence.packet));
 });
}

test('a historical review cannot inherit a substituted treatment root from otherwise valid SQL evidence',()=>{
 const p=clone(evidence.reviewPacket);p.treatmentOriginal.rootId=foreign;
 assert.ok(treatmentCareReviewPacketIssue(p));
});

test('a split review root and foreign review scope remain rejected in actual SQL evidence',()=>{
 const split=clone(evidence.reviewReceipt.original);split.rootId=foreign;
 assert.ok(treatmentCareReviewOriginalIssue(split,evidence.reviewPacket));
 const foreignScope=clone(evidence.reviewReceipt.original);foreignScope.clientId=foreign;
 assert.ok(treatmentCareReviewOriginalIssue(foreignScope,evidence.reviewPacket));
});
