#!/usr/bin/env python3
"""Measure existing PNGs for the Web renderer; never rewrite image pixels.

Run with the existing Pillow-equipped tooling. --check verifies the committed
measurements without writing files. Alpha values below 4 are export speckles,
not the visible shadow; the solid motif is measured separately at alpha 32.
"""

from argparse import ArgumentParser
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/healthos/widgets-premium"
OUTPUT = ROOT / "src/liquid-command/components/desktopArtworkAssets.shared.ts"


def bounds(alpha, threshold):
    measured = alpha.point(lambda value: 255 if value >= threshold else 0).getbbox()
    if measured is None:
        raise ValueError(f"Artwork has no visible pixels at alpha {threshold}")
    left, top, right, bottom = measured
    return [left, top, right - left, bottom - top]


def generate():
    lines = [
        "// Generated by scripts/generate-desktop-artwork-metadata.py. No PNG pixels are changed.",
        "// Static requires bind measurements to the actual Expo asset, not URL/filename guesses.",
        "import type { ImageSourcePropType } from 'react-native';",
        "import type { DesktopArtworkGeometry } from './desktopArtworkGeometry.shared';",
        "",
        "export type DesktopArtworkAsset = DesktopArtworkGeometry & {",
        "  source: ImageSourcePropType;",
        "  path: string;",
        "  bytes: number;",
        "};",
        "",
        "export const DESKTOP_ARTWORK_ASSETS: readonly DesktopArtworkAsset[] = [",
    ]
    for path in sorted(ASSETS.rglob("*.png")):
        with Image.open(path) as image:
            alpha = image.convert("RGBA").getchannel("A")
            body = bounds(alpha, 32)
            shadow = bounds(alpha, 4)
            relative = path.relative_to(ROOT).as_posix()
            lines.extend([
                "  {",
                f"    source: require('../../../{relative}'),",
                f"    path: '{relative}',",
                f"    bytes: {path.stat().st_size},",
                f"    pixelSize: [{image.width}, {image.height}], contentBounds: {body}, paintBounds: {shadow},",
                "  },",
            ])
    lines.extend([
        "];",
        "",
    ])
    return "\n".join(lines)


def main():
    parser = ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != output:
            raise SystemExit("Desktop artwork measurements are outdated; rerun the generator.")
        print("Desktop artwork measurements match all source PNGs.")
    else:
        OUTPUT.write_text(output)
        print(f"Measured {len(list(ASSETS.rglob('*.png')))} source PNGs.")


if __name__ == "__main__":
    main()
