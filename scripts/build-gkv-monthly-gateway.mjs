import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const target=resolve(root,'api/gkv/monthly-originals.mjs');
const result=await build({absWorkingDir:root,entryPoints:['services/gkv/monthly-gateway-entry.mjs'],bundle:true,write:false,
  platform:'node',format:'esm',target:'node20',charset:'utf8',legalComments:'none',metafile:true,
  banner:{js:'// Generated by scripts/build-gkv-monthly-gateway.mjs. Do not edit; stateless monthly gateway.'}});
// The deployed gateway must need only built-in Node modules, not a TS loader,
// CommonJS-to-ESM require bridge, worker archive or private host dependencies.
for(const output of Object.values(result.metafile.outputs))for(const dependency of output.imports){
  if(!dependency.external || !dependency.path.startsWith('node:'))throw Error('MONTHLY_GATEWAY_EXTERNAL_DEPENDENCY');
}
const content=result.outputFiles[0].text;
if(process.argv.includes('--check')){
  if(await readFile(target,'utf8').catch(()=>'')!==content)throw Error('Monthly gateway differs from shared source. Run node scripts/build-gkv-monthly-gateway.mjs.');
}else await writeFile(target,content);
console.log('Monthly gateway bundle verified.');
