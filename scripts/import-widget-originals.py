#!/usr/bin/env python3
"""Import a bounded release of recovered originals; retain every master byte."""
import argparse
import hashlib
import io
import json
import pathlib
import zipfile

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'src/liquid-command/components/widgetRasterArtworkManifest.shared.json'
ASSETS = ROOT / 'src/liquid-command/components/widgetRasterArtworkAssets.ts'


def part_for(identity):
    if identity.startswith(('/office', '/assist', '/business/office')):
        return 'office-assist'
    if identity.startswith(('/pflege', '/stationaer', '/beratung')):
        return 'care'
    return 'remaining'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('archive', type=pathlib.Path)
    parser.add_argument('--part', choices=['office-assist', 'care', 'remaining'], required=True)
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {'version': 'originals-20261106-v1', 'artworks': []}
    entries = {entry['identity']: entry for entry in manifest['artworks']}
    imported = 0
    with zipfile.ZipFile(args.archive) as archive:
        recovered = json.loads(archive.read('zuordnung.json'))
        for artwork in recovered['artworks']:
            assignments = artwork['widget_assignments']
            if not assignments:
                continue
            if len(assignments) != 1:
                raise ValueError('One original must belong to exactly one function')
            assignment = assignments[0]
            if part_for(assignment['identity']) != args.part:
                continue
            image_bytes = archive.read(artwork['file'])
            digest = hashlib.sha256(image_bytes).hexdigest()
            if digest != artwork['sha256']:
                raise ValueError(f"Original checksum differs: {artwork['file']}")
            image = Image.open(io.BytesIO(image_bytes))
            image.load()
            if image.size != (1254, 1254) or image.mode != 'RGBA':
                raise ValueError(f"Invalid original: {artwork['file']}")
            identifier = assignment['id']
            if not identifier.replace('-', '').isalnum():
                raise ValueError('Unsafe artwork identifier')
            relative = pathlib.Path('widget-artwork') / manifest['version'] / identifier
            folder = ROOT / 'public' / relative
            folder.mkdir(parents=True, exist_ok=True)
            variants = {}
            for size, width in [('small', 192), ('medium', 512), ('large', 1254)]:
                target = folder / f'{size}.png'
                if size == 'large':
                    target.write_bytes(image_bytes)
                else:
                    image.resize((width, width), Image.Resampling.LANCZOS).save(target, compress_level=9)
                variants[size] = {'path': '/' + (relative / target.name).as_posix(), 'width': width,
                                  'sha256': hashlib.sha256(target.read_bytes()).hexdigest()}
            entries[assignment['identity']] = {
                'id': identifier, 'identity': assignment['identity'], 'label': assignment['label'],
                'part': args.part, 'sourceSha256': digest, 'variants': variants,
            }
            imported += 1
    manifest['artworks'] = sorted(entries.values(), key=lambda entry: entry['identity'])
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    lines = ["// Generated by scripts/import-widget-originals.py from the shared manifest.",
             "import type { ImageSourcePropType } from 'react-native';",
             "export type WidgetRasterImages = Record<'small' | 'medium' | 'large', ImageSourcePropType>;",
             "export const WIDGET_RASTER_IMAGES: Record<string, WidgetRasterImages> = {"]
    for entry in manifest['artworks']:
        lines.append(f"  {json.dumps(entry['id'])}: {{")
        for size, variant in entry['variants'].items():
            lines.append(f"    {size}: require('../../../public{variant['path']}'),")
        lines.append('  },')
    lines.extend(['};', ''])
    ASSETS.write_text('\n'.join(lines))
    print(f"Imported {imported} original masters for {args.part}; total {len(manifest['artworks'])} functions.")


if __name__ == '__main__':
    main()
