import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'supabase/functions/complete-client-intake/runtime.generated.js');
const result = await build({ absWorkingDir: root, entryPoints: ['src/features/intakeDocuments/intakeCompletionVerification.ts'], bundle: true, write: false, platform: 'neutral', format: 'esm', target: 'es2022', minify: false, legalComments: 'none', banner: { js: '// Generated by scripts/build-intake-edge-runtime.mjs. Do not edit; shared App/Edge verifier.' } });
const content = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== content) throw new Error('Intake Edge runtime differs from shared source. Run node scripts/build-intake-edge-runtime.mjs.');
} else await writeFile(target, content);
